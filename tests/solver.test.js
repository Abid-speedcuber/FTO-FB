test("optimal solutions exactly match independent exhaustive shallow search", () => {
  for (const [text, color] of [
    ["R U F", 0],
    ["BR U' BL", 1],
    ["R F'", 0],
    ["U L", 1],
  ]) {
    const sc = parseScramble(text),
      found = [];
    const r = solve(get(color), sc, {
      onSolution: (s) => {
        found.push(s.moves.join(","));
        assert.ok(matchingGoal(stickerPositions([...sc, ...s.moves]), color));
      },
    });
    const expected = brute(sc, color, r.depth);
    assert.deepEqual(found.sort(), expected.sort());
  }
});
test("long scramble solutions replay to a valid 12-piece block", () => {
  const sc = parseScramble(
    "R U F' L BR U' BL D R' B F U L' D BR' F R U' BL' B",
  );
  for (let color = 0; color < 8; color++) {
    const found = [];
    const r = solve(get(color), sc, {
      onSolution: (s) => found.push(s),
      maxNodes: 100000000,
    });
    assert.ok(r.depth > 0);
    assert.ok(found.length);
    for (const s of found) {
      const positions = stickerPositions([...sc, ...s.moves]);
      const target = matchingGoal(positions, color);
      assert.ok(target);
      const visible = candidateMask(color);
      assert.equal(visible.size, 30);
      const pieces = physicalGroups().filter((g) =>
        g.some((id) => visible.has(id)),
      );
      assert.equal(pieces.length, 18);
      assert.ok(pieces.every((g) => g.every((id) => visible.has(id))));
      assert.ok(
        target.first.every(([slot]) => visible.has(positions.indexOf(slot))),
      );
    }
  }
});

