import test from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { prepare, solve, initialCoordinates } from "../src/model/search.js";
import {
  parseScramble,
  permutations,
  matchingGoal,
  stickerPositions,
  goalsFor,
  physicalGroups,
  solved,
  candidateMask,
  moves,
} from "../src/model/fto.js";
const tables = new Map();
const get = (color) => {
  if (!tables.has(color)) tables.set(color, prepare(color));
  return tables.get(color);
};
function brute(scramble, color, max) {
  const root = stickerPositions(scramble);
  let level = [{ ps: root, path: [] }];
  for (let d = 0; d <= max; d++) {
    const found = level.filter((s) => matchingGoal(s.ps, color));
    if (found.length) return found.map((s) => s.path.join(","));
    level = level.flatMap((s) =>
      permutations.flatMap((p, m) =>
        m >> 1 === s.path.at(-1) >> 1 && s.path.length
          ? []
          : [{ ps: s.ps.map((x) => p[x]), path: [...s.path, m] }],
      ),
    );
  }
  return [];
}
test("parser validates the complete standard face-turn notation", () => {
  assert.deepEqual(parseScramble("U BR’ BL2 d"), [0, 7, 13, 14]);
  assert.throws(() => parseScramble("R nope"));
  assert.deepEqual(parseScramble(""), []);
});
test("turns have order three and inverse permutations agree", () => {
  for (let m = 0; m < 16; m++)
    for (let p = 0; p < 72; p++) {
      assert.equal(permutations[m][permutations[m ^ 1][p]], p);
      assert.equal(permutations[m][permutations[m][permutations[m][p]]], p);
    }
});
test("viewer mask has 18 complete pieces and each FB has 12", () => {
  for (let color = 0; color < 8; color++) {
    const bases = goalsFor(color).filter((v) =>
      v.first.every(([p, c]) => solved[p].color === c),
    );
    assert.equal(bases.length, 3);
    const mask = candidateMask(color);
    const pieces = physicalGroups().filter((g) => g.some((p) => mask.has(p)));
    assert.equal(pieces.length, 18);
    assert.ok(pieces.every((g) => g.every((p) => mask.has(p))));
    for (const b of bases)
      assert.equal(
        physicalGroups().filter((g) =>
          g.some((p) => b.first.some(([id]) => id === p)),
        ).length,
        12,
      );
  }
});
test("all colors have 12 reachable poses per omitted triple and solved needs no moves", () => {
  for (let color = 0; color < 8; color++) {
    const t = get(color);
    assert.deepEqual(
      t.options.map((o) => o.targets.length),
      [12, 12, 12],
    );
    const results = [];
    assert.equal(solve(t, [], { onSolution: (s) => results.push(s) }).depth, 0);
    assert.equal(results.length, 1);
    assert.ok(matchingGoal(stickerPositions(results[0].moves), color));
  }
});
test("optimal solutions exactly match independent exhaustive shallow search", () => {
  for (const [text, color] of [
    ["R U F", 0],
    ["BR U' BL", 1],
    ["R F'", 0],
    ["U L", 1],
  ]) {
    const sc = parseScramble(text),
      found = [];
    const r = solve(get(color), sc, {
      onSolution: (s) => {
        found.push(s.moves.join(","));
        assert.ok(matchingGoal(stickerPositions([...sc, ...s.moves]), color));
      },
    });
    const expected = brute(sc, color, r.depth);
    assert.deepEqual(found.sort(), expected.sort());
  }
});
test("long scramble solutions replay to a valid 12-piece block", () => {
  const sc = parseScramble(
    "R U F' L BR U' BL D R' B F U L' D BR' F R U' BL' B",
  );
  for (let color = 0; color < 8; color++) {
    const found = [];
    const r = solve(get(color), sc, {
      onSolution: (s) => found.push(s),
      maxNodes: 100000000,
    });
    assert.ok(r.depth > 0);
    assert.ok(found.length);
    for (const s of found) {
      const positions = stickerPositions([...sc, ...s.moves]);
      const target = matchingGoal(positions, color);
      assert.ok(target);
      const visible = candidateMask(color);
      assert.equal(visible.size, 30);
      const pieces = physicalGroups().filter((g) =>
        g.some((id) => visible.has(id)),
      );
      assert.equal(pieces.length, 18);
      assert.ok(pieces.every((g) => g.every((id) => visible.has(id))));
      assert.ok(
        target.first.every(([slot]) => visible.has(positions.indexOf(slot))),
      );
    }
  }
});

// Frozen independent csTimer cubie permutations, not generated by this solver.
const reference = JSON.parse(
  readFileSync(
    new URL("./fixtures/cstimer-permutations.json", import.meta.url),
    "utf8",
  ),
);
test("every CIF face turn and inverse matches all 72 csTimer sticker destinations", () => {
  for (const [name, expected] of Object.entries(reference.turns)) {
    assert.deepEqual(
      [...stickerPositions(parseScramble(name))],
      expected,
      name,
    );
  }
  assert.deepEqual(
    [...stickerPositions(parseScramble(reference.scramble))],
    reference.positions,
  );
});
test("reported scramble is solved using standard CIF input and output", () => {
  const scramble = parseScramble(reference.scramble);
  const oldOutput = parseScramble("L D' L' U BL L D B");
  assert.equal(
    matchingGoal(stickerPositions([...scramble, ...oldOutput]), 0),
    undefined,
  );
  let count = 0;
  const result = solve(get(0), scramble, {
    onSolution: (solution) => {
      let positions = [...reference.positions];
      for (const move of solution.moves)
        positions = positions.map((p) => reference.turns[moves[move].name][p]);
      assert.ok(matchingGoal(Uint8Array.from(positions), 0));
      count++;
    },
    maxNodes: 100000000,
  });
  assert.equal(result.depth, 10);
  assert.equal(result.count, 56);
  assert.equal(count, 56);
});
