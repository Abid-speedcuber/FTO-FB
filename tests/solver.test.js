      assert.equal(pieces.filter((g) => g.length === 4).length, 1);
      assert.equal(pieces.filter((g) => g.length === 2).length, 3);
      assert.equal(pieces.filter((g) => g.length === 1).length, 5);
      assert.ok([...firstCenter].every((id) => ids.has(id)));
